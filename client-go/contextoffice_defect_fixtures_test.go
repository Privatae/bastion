// in BOTH branches — measured, `<w:t>` texts are:
//
//	[before, BOXPROBE UNIQUE CALLOUT WORDS, BOXPROBE UNIQUE CALLOUT WORDS,
//	 " ", after]
//
// Word writes the identical shape. A consumer picks ONE branch; walking both
